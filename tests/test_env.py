        if token == registry.up_block_markers[1] or token == registry.ac_block_markers[1]:
            # returning back to the solve context from either up or ac
            prev_env_pos = float("inf")  # so that the position goes up only by 1 this iteration
        env_pos = len(env.get_current_input())

        pos += max(1, env_pos - prev_env_pos)

        # if step > 180:
