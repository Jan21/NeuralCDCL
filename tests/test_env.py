    sample = tokenized_dataset.sample_solve_traces(n=1)[0]

    # Build environment
    registry = CommandRegistry(cfg, tokenizer)
    scratchpad = CDCLScratchpad(sample.input_clauses['input_ids'], registry)
    parser = CommandParser(registry)
    env = AutoregressiveCDCLEnvironment(registry, scratchpad, parser)

    # We'll step through the solve trace, one token at a time
    solve_tokens = sample.solve["input_ids"]
    composed_tokens = sample.compose(
        up_call_token=registry.action_cmd_tokens["CALL_UNIT_PROPAGATION"],
        ac_call_token=registry.action_cmd_tokens["CALL_ANALYZE_CONFLICT"]
    )

